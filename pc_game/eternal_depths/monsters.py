MONSTERS = {m["key"]: m for m in MONSTERS_LIST}


def by_dlvl(dlvl, count=1, rng=None):
    """Return a sample of monster keys appropriate for level."""
    import random
    rng = rng or random
    pool = []
    for m in MONSTERS_LIST:
        ml = m["dlvl"]
        diff = abs(ml - dlvl)
        if ml > dlvl + 2 or m["key"] == "eternal_one":
            continue
        weight = max(1, 8 - diff * 2)
        pool.extend([m["key"]] * weight)
    return [rng.choice(pool) for _ in range(count)]


